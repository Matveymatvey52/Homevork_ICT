#pragma once

// Структура-результат разбора аргументов командной строки.
// Хранит только то, что нужно остальной программе для работы.
struct CliOptions {
    int max_value = 100;       // максимальное загадываемое число (не включительно)
    bool show_table_only = false; // true, если передан флаг -table
    bool has_error = false;    // true, если аргументы заданы некорректно
};

// Разбирает argc/argv и возвращает заполненную структуру CliOptions.
// Поддерживаемые аргументы:
//   -max <N>    задать верхнюю границу загадываемого диапазона [0; N)
//   -level <N>  задать уровень сложности (1, 2 или 3) вместо -max
//   -table      сразу вывести таблицу рекордов и завершить работу
// Одновременное указание -max и -level считается ошибкой (has_error = true).
CliOptions parse_cli_options(int argc, char** argv);
